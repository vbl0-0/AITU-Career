import { test, expect } from '@playwright/test';
import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const createdEmails: string[] = [];
const createdJobTitles: string[] = [];
const envFile = existsSync(resolve('..', '.env')) ? readFileSync(resolve('..', '.env'), 'utf8') : '';
const demoPassword = process.env.DEMO_PASSWORD || envFile.split(/\r?\n/).find(line => line.startsWith('DEMO_PASSWORD='))?.slice('DEMO_PASSWORD='.length);

test.afterAll(async ({ request }) => {
  if (!demoPassword || (!createdEmails.length && !createdJobTitles.length)) return;
  const login = await request.post('/api/auth/login', { data: { email: 'admin.demo@aitu.edu.kz', password: demoPassword } });
  if (!login.ok()) return;
  const headers = { Authorization: 'Bearer ' + (await login.json()).access_token };
  const response = await request.get('/api/admin/users', { headers });
  if (response.ok()) for (const user of await response.json()) {
    if (createdEmails.includes(user.email)) expect((await request.delete('/api/admin/users/' + user.id, { headers })).ok()).toBeTruthy();
  }
  const jobs = await request.get('/api/admin/jobs', { headers });
  if (jobs.ok()) for (const job of await jobs.json()) {
    if (createdJobTitles.includes(job.title)) expect((await request.delete('/api/admin/jobs/' + job.id, { headers })).ok()).toBeTruthy();
  }
  await request.post('/api/auth/logout');
});

